def plural(n: int, one: str, few: str, many: str) -> str:
    n100, n10 = n % 100, n % 10
    if 11 <= n100 <= 14:
        return many
    return one if n10 == 1 else few if 2 <= n10 <= 4 else many


def trio(n: int, feminine: bool = False) -> str:
    parts = []
    if n >= 100:
        parts.append(HUNDREDS[n // 100]); n %= 100
    if n >= 20:
        parts.append(TENS[n // 10]); n %= 10
    elif n >= 10:
        parts.append(TEENS[n - 10]); n = 0
    if n:
        parts.append("одна" if feminine and n == 1 else "две" if feminine and n == 2 else ONES[n])
    return " ".join(parts)


def words(n: int) -> str:
    th, rest = divmod(n, 1000)
    chunks = []
    if th:
        chunks.append(f"{trio(th, True)} {plural(th, 'тысяча', 'тысячи', 'тысяч')}")
    if rest:
        chunks.append(trio(rest))
    return " ".join(chunks) or "ноль"


def usd(n: float) -> str:
    whole = int(n)
    cents = round((n - whole) * 100)
    num = f"{whole:,}".replace(",", " ")
    tail = f",{cents:02d}" if cents else ""
    cents_w = f" {cents:02d} {plural(cents, 'цент', 'цента', 'центов')}" if cents else ""
    return (f"{num}{tail} ({words(whole)}) {plural(whole, 'доллар', 'доллара', 'долларов')} США{cents_w}")


