def _plural(k: int, one: str, few: str, many: str) -> str:
    if 11 <= k % 100 <= 14:
        return many
    return one if k % 10 == 1 else few if 2 <= k % 10 <= 4 else many


def _trio(k: int, fem: bool = False) -> str:
    out = []
    if k >= 100:
        out.append(HUNDREDS[k // 100]); k %= 100
    if k >= 20:
        out.append(TENS[k // 10]); k %= 10
    elif k >= 10:
        out.append(TEENS[k - 10]); k = 0
    if k:
        out.append("одна" if fem and k == 1 else "две" if fem and k == 2 else ONES[k])
    return " ".join(out)


def words(v: int) -> str:
    """Сумма прописью: цифру в договоре нельзя «поправить» после подписания."""
    mil, rest = divmod(v, 1_000_000)
    th, u = divmod(rest, 1000)
    parts = []
    if mil:
        parts.append(f"{_trio(mil)} {_plural(mil, 'миллион', 'миллиона', 'миллионов')}")
    if th:
        parts.append(f"{_trio(th, True)} {_plural(th, 'тысяча', 'тысячи', 'тысяч')}")
    if u:
        parts.append(_trio(u))
    return " ".join(parts)


def som(v: int) -> str:
    return f"{n(v)} ({words(v)}) сум"


