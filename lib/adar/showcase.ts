/**
 * Витринная обвязка: полоса с вариантами и смета.
 *
 * Она существует только на нашей демонстрационной площадке. Признак тот же,
 * что и у витринного корня, — `SHOWCASE_ROOT` в `.env.local`: на сервере
 * заказчика этой переменной нет, и страница собирается без обвязки. Значение
 * читается на сервере во время сборки, так что в отданной разметке её просто
 * не остаётся — не спрятана стилями, а отсутствует.
 *
 * Порядок именно такой, а не «выключить на боевом»: забытая переменная должна
 * приводить к чистому сайту, а не к чужим ценам на виду у заказчика.
 */
export const showcaseChrome = process.env.SHOWCASE_ROOT === "true";

/**
 * Сметы и цены нашей работы на витрине: суммы у вариантов, построчные
 * сметы, конструктор допников с ценами и версия для печати.
 *
 * Выключены по умолчанию: витрину открывают не только заказчик, но и все,
 * кто пришёл по ссылке из кейса студии, — сколько стоит работа, им видеть
 * незачем. Три варианта, их сравнение и переходы между ними остаются.
 *
 * Включается строкой `ADAR_PRICING=on` в `.env.local` — например, перед
 * встречей, где смету разбирают вместе. Как и `showcaseChrome`, признак
 * читается на сервере при сборке: при выключенном в разметке и в данных
 * страницы цифр нет вовсе, а не спрятаны стилями.
 */
export const showcasePricing = showcaseChrome && process.env.ADAR_PRICING === "on";
