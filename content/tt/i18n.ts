/**
 * Два языка макета: русский и казахский.
 *
 * У «Транстелекома» на сайте три языка, и казахский — не украшение: это
 * государственная компания в РК. Поэтому в макете он полный, а не
 * «заглушка на главной». Английский в макет не берём: обещать перевод,
 * которого нет, хуже, чем не обещать вовсе.
 *
 * Все казахские строки ниже — либо прямо с их сайта (описание компании,
 * миссия, история, названия услуг, названия городов), либо переведены
 * по их же формулировкам. Ничего машинного «на глаз» здесь нет: если
 * фразы на их сайте не нашлось, она собрана из их слов.
 */

export type Lang = "ru" | "kk";

export const langs: { id: Lang; label: string; full: string }[] = [
  { id: "ru", label: "Ru", full: "Русский" },
  { id: "kk", label: "Kz", full: "Қазақша" },
];

/** Пара строк: русская и казахская. */
export type Pair = { ru: string; kk: string };

export function t(pair: Pair, lang: Lang): string {
  return pair[lang];
}
