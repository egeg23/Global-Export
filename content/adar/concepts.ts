export function getConcept(id: Concept["id"]): Concept {
  const concept = concepts.find((item) => item.id === id);
  // Идентификаторы приходят из статических маршрутов, так что промах здесь —
  // это опечатка в коде, а не отсутствующая страница.
  if (!concept) throw new Error(`Неизвестная концепция: ${id}`);
  return concept;
}

