export const fallback =
  "Понял вопрос. Сейчас уточню у цеха и вернусь с точным ответом — а пока " +
  "соберите состав в калькуляторе выше, я увижу его вместе с заявкой.";

/** Тема вопроса решается по первому совпадению: порядок в списке и есть приоритет. */
export function replyTo(question: string): string {
  return replies.find((reply) => reply.match.test(question))?.text ?? fallback;
}
