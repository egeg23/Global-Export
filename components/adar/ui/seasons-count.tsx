"use client";

import { useSyncExternalStore } from "react";

const noSubscription = () => () => {};

/**
 * Порядковые до тридцатого — этого хватит до 2041 года, а дальше строка
 * сама перейдёт на «31-й сезон» и останется верной.
 */
const ordinals = [
  "первый",
  "второй",
  "третий",
  "четвёртый",
  "пятый",
  "шестой",
  "седьмой",
  "восьмой",
  "девятый",
  "десятый",
  "одиннадцатый",
  "двенадцатый",
  "тринадцатый",
  "четырнадцатый",
  "пятнадцатый",
  "шестнадцатый",
  "семнадцатый",
  "восемнадцатый",
  "девятнадцатый",
  "двадцатый",
  "двадцать первый",
  "двадцать второй",
  "двадцать третий",
  "двадцать четвёртый",
  "двадцать пятый",
  "двадцать шестой",
  "двадцать седьмой",
  "двадцать восьмой",
  "двадцать девятый",
  "тридцатый",
];

function ordinal(count: number): string {
  const word = ordinals[count - 1];
  if (!word) return `${count}-й`;
  return word[0].toUpperCase() + word.slice(1);
}

/**
 * Какой сезон у компании идёт сейчас.
 *
 * Считается, а не пишется руками: строку «Пятнадцатый сезон подряд» через год
 * после сдачи пришлось бы править вручную на сервере заказчика, а её никто
 * там править не будет. Год берётся в браузере — на статической странице
 * `new Date()` выполнился бы при сборке и застыл на ней.
 */
export function SeasonsCount({ since, buildYear }: { since: number; buildYear: number }) {
  const year = useSyncExternalStore(
    noSubscription,
    () => new Date().getFullYear(),
    () => buildYear,
  );

  return <>{ordinal(Math.max(1, year - since + 1))} сезон подряд</>;
}
