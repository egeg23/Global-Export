export function ArsenalLogo({
  className,
  title = "Arsenal D",
  trigger = "intro",
}: {
  className?: string;
  title?: string;
  /** Когда играть появление: после заставки студии или при въезде в экран. */
  trigger?: "intro" | "view";
}) {
  const id = useId().replace(/:/g, "");
  const ref = useRef<SVGSVGElement>(null);
  const [shown, setShown] = useState(false);

  useEffect(() => {
    if (trigger === "intro") return whenDevuzIntroDone(() => window.requestAnimationFrame(() => setShown(true)));
    const node = ref.current;
    if (!node) return;
    const observer = new IntersectionObserver((entries) => {
      if (entries.some((entry) => entry.isIntersecting)) {
        setShown(true);
        observer.disconnect();
      }
    });
    observer.observe(node);
    return () => observer.disconnect();
  }, [trigger]);

  const dShift = "translate(393 8.4) scale(0.99)";

  return (
    <svg ref={ref} viewBox="0 -8 480 92" role="img" aria-label={title} className={cn("al-logo", shown && "is-in", className)}>
      <defs>
        <linearGradient id={`${id}-red`} x1="0" y1="0" x2="1" y2="1">
          <stop offset="0" stopColor="#ff4a3d" />
          <stop offset="0.55" stopColor="#e1121b" />
          <stop offset="1" stopColor="#a30a16" />
        </linearGradient>
        <linearGradient id={`${id}-gloss`} x1="0" y1="0" x2="1" y2="0">
          <stop offset="0" stopColor="#fff" stopOpacity="0" />
          <stop offset="0.5" stopColor="#fff" stopOpacity="0.75" />
          <stop offset="1" stopColor="#fff" stopOpacity="0" />
        </linearGradient>
        {/* Вырез под звездой — дырка в чаше, а не белое пятно: на тёмном фоне
            «Премиума» сквозь неё виден фон. */}
        <mask id={`${id}-notch`} maskUnits="userSpaceOnUse" x="-10" y="-20" width="110" height="110">
          <rect x="-10" y="-20" width="110" height="110" fill="#fff" />
          <path d={D.notch} fill="#000" />
        </mask>
        <clipPath id={`${id}-clip`}>
          {WORD.map((d, index) => (
            <path key={index} d={d} />
          ))}
          <g transform={dShift}>
            <path d={D.stem} />
            <path d={D.bowl} />
            <path d={D.star} />
          </g>
        </clipPath>
      </defs>
      <g fill="currentColor">
        {WORD.map((d, index) => (
          <path key={index} d={d} className="al-ch" style={{ "--c": index } as React.CSSProperties} />
        ))}
      </g>
      <g transform={dShift}>
        <g className="al-bowl">
          <path d={D.bowl} fill={`url(#${id}-red)`} mask={`url(#${id}-notch)`} />
        </g>
        <g className="al-stem">
          <path d={D.stem} fill={`url(#${id}-red)`} />
          <path d={D.crease} fill="#5c0710" opacity="0.45" />
        </g>
        <path d={D.star} className="al-star" fill={`url(#${id}-red)`} stroke="#8a0812" strokeWidth="0.8" strokeLinejoin="round" />
      </g>
      <g clipPath={`url(#${id}-clip)`} aria-hidden="true">
        <rect className="al-gloss" x="-120" y="-10" width="110" height="100" fill={`url(#${id}-gloss)`} />
      </g>
    </svg>
  );
}
