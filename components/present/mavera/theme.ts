/** Порядок пакетов — чтобы понимать, доступен ли экран в выбранном варианте. */
const rank: Record<TierId, number> = { standard: 0, lux: 1, premium: 2 };

export function screensFor(tier: TierId): ScreenMeta[] {
  return screens.filter((screen) => !screen.from || rank[tier] >= rank[screen.from]);
}

export function lockedIn(tier: TierId): ScreenMeta[] {
  return screens.filter((screen) => screen.from && rank[tier] < rank[screen.from]);
}

